def _load_usage() -> dict:
    f = _usage_file()
    if f.exists():
        try:
            return json.loads(f.read_text(encoding='utf-8'))
        except Exception:
            pass
    return {}


def _save_usage(usage: dict) -> None:
    f = _usage_file()
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        tmp = f.parent / f'.tmp_{f.name}'
        tmp.write_text(json.dumps(usage), encoding='utf-8')
        os.replace(tmp, f)
    except Exception as exc:
        logger.warning(f'caption_usage save: {exc}')


def _filter_cooldown(entries: list, cooldown_days: int) -> list:
    """Отсеять подписи, использованные недавно. Без id — не фильтруем."""
    if cooldown_days <= 0:
        return entries
    try:
        usage = _load_usage()
    except Exception:
        return entries
    threshold = time.time() - cooldown_days * 86400
    fresh = [
        e for e in entries
        if not e.get('id') or float(usage.get(e['id'], 0)) < threshold
    ]
    return fresh or entries


def _record_usage(entry: dict) -> None:
    entry_id = entry.get('id')
    if not entry_id:
        return
    try:
        usage = _load_usage()
        now = time.time()
        usage[entry_id] = now
        # Чистим записи старше 60 дней, чтобы файл не рос бесконечно
        usage = {k: v for k, v in usage.items() if now - float(v) < 60 * 86400}
        _save_usage(usage)
    except Exception as exc:
        logger.warning(f'caption_usage record: {exc}')


def _ucb_category(categories: list[str], media_format: str) -> str | None:
    """Выбор семейства бандитом по статистике трекера. None — мало данных."""
    try:
        from services.bandit import stats_to_arms, ucb_choose
        from services.tracker import get_caption_stats
        stats = get_caption_stats(media_type=media_format)
    except Exception:
        return None
    arms = stats_to_arms(stats, names=categories)
    if sum(a['trials'] for a in arms) < UCB_MIN_TRIALS:
        return None
    return ucb_choose(arms)


def get_random_entry(media_format: str = 'photo') -> dict:
    lib = load_library()
    entries = lib.get('entries') or UNIVERSAL_ENTRIES
    if not entries:
        return {'text': '', 'tags': ''}

    by_category: dict[str, list] = {}
    for entry in entries:
        # Записи без категории (добавленные через UI) считаем engagement
        category = entry.get('category', 'engagement')
        if category == 'emotion':  # легаси-категория из прошлой версии
            category = 'engagement'
        by_category.setdefault(category, []).append(entry)

    all_weights = lib.get('category_weights') or {}
    weights_cfg = all_weights.get(media_format) or FORMAT_CATEGORY_WEIGHTS.get(
        media_format, CATEGORY_WEIGHTS
    )

    categories = [
        c for c in CATEGORY_WEIGHTS
        if c in by_category and weights_cfg.get(c, CATEGORY_WEIGHTS[c]) > 0
    ]
    if not categories:
        return random.choice(entries)

    category = None
    if random.random() > UCB_EPSILON:
        category = _ucb_category(categories, media_format)
    if not category:
        weights = [weights_cfg.get(c, CATEGORY_WEIGHTS[c]) for c in categories]
        category = random.choices(categories, weights=weights, k=1)[0]

    pool = _filter_cooldown(by_category[category], int(lib.get('caption_cooldown_days', CAPTION_COOLDOWN_DAYS)))
    stop_words = lib.get('stop_words') or []
    if stop_words:
        clean = [e for e in pool if not caption_has_stop_word(e.get('text', ''), stop_words)]
        pool = clean or pool
    entry = random.choice(pool)
    _record_usage(entry)
    return entry


def get_random_cta() -> str:
    lib = load_library()
    if not lib.get('cta_enabled', False):
        return ''
    ctas = lib.get('ctas') or UNIVERSAL_CTAS
    return random.choice(ctas) if ctas else ''


def _iter_hashtags(value) -> Iterable[str]:
    if not value:
        return []
    if isinstance(value, str):
        items = value.replace('\n', ' ').split()
    else:
        items = []
        for item in value:
            items.extend(str(item).replace('\n', ' ').split())

    tags = []
    for item in items:
        item = item.strip().strip(',')
        if not item:
            continue
        if not item.startswith('#'):
            item = f'#{item}'
        if len(item) > 1:
            tags.append(item)
    return tags


def dedupe_hashtags(*values) -> str:
    result = []
    seen = set()
    for value in values:
        for tag in _iter_hashtags(value):
            key = tag.lower()
            if key in seen:
                continue
            seen.add(key)
            result.append(tag)
    return ' '.join(result)


# ── Защита подписи от стоп-слов и запрещённых хэштегов ────────────


def _normalize_tag(tag: str) -> str:
    t = str(tag).strip().lower()
    return t if t.startswith('#') else f'#{t}'


def filter_forbidden_hashtags(tags: list[str], forbidden) -> list[str]:
    """Убрать из списка тегов запрещённые (сравнение без регистра, с/без #)."""
    if not forbidden:
        return tags
    banned = {_normalize_tag(t) for t in forbidden if str(t).strip()}
    return [t for t in tags if t.lower() not in banned]


def caption_has_stop_word(text: str, stop_words) -> bool:
    """True, если в тексте встречается любое стоп-слово (без регистра)."""
    if not text or not stop_words:
        return False
    low = text.lower()
    return any(str(w).strip().lower() in low for w in stop_words if str(w).strip())


# ── Разведение хэштегов между каналами ───────────────────────────
# Один и тот же набор тегов в разных группах VK расценивает как рассылку
# дубля. Делим общий журнал использованных наборов между профилями и
# подбираем для текущего канала набор, не совпадающий с недавним чужим.


_HASHTAG_DIVERSITY_WINDOW_DAYS = 2


def _shared_hashtag_file() -> Path:
    return STORAGE_DIR / '_shared' / 'hashtag_usage.json'


def _load_shared_hashtags() -> dict:
    f = _shared_hashtag_file()
    if f.exists():
        try:
            return json.loads(f.read_text(encoding='utf-8'))
        except Exception:
            return {}
    return {}


def _save_shared_hashtags(data: dict) -> None:
    f = _shared_hashtag_file()
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        tmp = f.parent / f'.tmp_{f.name}'
        tmp.write_text(json.dumps(data, ensure_ascii=False), encoding='utf-8')
        os.replace(tmp, f)
    except Exception as exc:
        logger.warning(f'hashtag_usage save: {exc}')


def diversify_hashtags(
    ordered: list[str],
    profile_id: str,
    window_days: int = _HASHTAG_DIVERSITY_WINDOW_DAYS,
) -> list[str]:
    """Выбрать до MAX_HASHTAGS тегов, не повторяя недавний набор чужого канала.

    Сохраняет приоритет порядка `ordered` (ручные → библиотека → конкуренты):
    сначала пробуем исходный срез, затем другие комбинации того же размера.
    Возвращает срез как есть, если развести нельзя (мало тегов/нет данных).
    """
    base = ordered[:MAX_HASHTAGS]
    if len(ordered) <= 1:
        return base
    try:
        data = _load_shared_hashtags()
    except Exception:
        return base

    threshold = time.time() - window_days * 86400
    others = {
        frozenset(t.lower() for t in entry.get('tags', []))
        for pid, entry in data.items()
        if pid != profile_id and float(entry.get('ts', 0)) >= threshold
    }

    chosen = base
    if others:
        from itertools import combinations
        size = min(MAX_HASHTAGS, len(ordered))
        for combo in combinations(ordered, size):
            candidate = list(combo)
            if frozenset(t.lower() for t in candidate) not in others:
                chosen = candidate
                break

    data[profile_id] = {'tags': chosen, 'ts': time.time()}
    _save_shared_hashtags(data)
    return chosen


def compose_caption_with_meta(
    existing_text: str = '',
    add_tags: bool = True,
    profile_tags=None,
    add_profile_tags: bool = False,
    extra_tags: list[str] | None = None,
    media_format: str = 'photo',
) -> tuple[str, dict]:
    """Собрать подпись и вернуть метаданные шаблона — для обучения в трекере."""
    lib = load_library()
    existing_text = (existing_text or '').strip()
    parts = []
    lib_tags = ''
    meta: dict = {}
    emoji_mode = lib.get('emoji_mode', True)

    if emoji_mode:
        # Без текстовых шаблонов: красивые смайлы + (иногда) призыв подписаться.
        # Хэштеги добавляются ниже общим путём. Метаданные пустые — семейства
        # подписей не обучаются в этом режиме.
        parts.append(random_emojis())
        if lib.get('cta_enabled', False) and random.random() < SUBSCRIBE_CTA_CHANCE:
            parts.append(random_subscribe_cta())
    elif lib.get('enabled', False):
        entry = get_random_entry(media_format)
        text = (entry.get('text') or '').strip()
        if text:
            parts.append(text)
            meta = {
                'caption_category': entry.get('category', 'engagement'),
                'caption_text': text,
                'caption_id': entry.get('id', ''),
            }
        if add_tags:
            lib_tags = entry.get('tags', '')
        cta = get_random_cta()
        if cta:
            parts.append(cta.strip())
    elif existing_text:
        parts.append(existing_text)

    manual_tags = list(profile_tags or []) if add_profile_tags else []
    # В эмодзи-режиме теги выбираем рандомно (а не всегда первые из списка).
    if emoji_mode:
        random.shuffle(manual_tags)
    competitor_tags = []
    if extra_tags and add_profile_tags:
        competitor_tags = random.sample(extra_tags, min(MAX_HASHTAGS, len(extra_tags)))

    # Приоритет при урезании до MAX_HASHTAGS: ручные теги канала → теги из
    # библиотеки → конкурентские. Свои теги важнее авто-подобранных.
    ordered = dedupe_hashtags(
        manual_tags,
        lib_tags if add_tags else '',
        competitor_tags,
    ).split()
    ordered = filter_forbidden_hashtags(ordered, lib.get('forbidden_hashtags') or [])
    chosen = diversify_hashtags(ordered, app_state.active_profile_id)
    tags = ' '.join(chosen)
    if tags:
        parts.append(tags)

    return '\n\n'.join(part for part in parts if part).strip(), meta


def compose_caption(
    existing_text: str = '',
    add_tags: bool = True,
    profile_tags=None,
    add_profile_tags: bool = False,
    extra_tags: list[str] | None = None,
    media_format: str = 'photo',
) -> str:
    text, _ = compose_caption_with_meta(
        existing_text,
        add_tags=add_tags,
        profile_tags=profile_tags,
        add_profile_tags=add_profile_tags,
        extra_tags=extra_tags,
        media_format=media_format,
    )
    return text


