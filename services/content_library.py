def _normalize_weights(raw) -> dict:
    """Нормализовать веса; легаси-плоский словарь {category: w} заменяется дефолтами."""
    normalized = {}
    for fmt, base in FORMAT_CATEGORY_WEIGHTS.items():
        fmt_raw = raw.get(fmt) if isinstance(raw, dict) else None
        if not isinstance(fmt_raw, dict):
            normalized[fmt] = dict(base)
            continue
        fmt_weights = {}
        for category, default in base.items():
            try:
                fmt_weights[category] = max(0, int(fmt_raw.get(category, default)))
            except (TypeError, ValueError):
                fmt_weights[category] = default
        normalized[fmt] = fmt_weights
    return normalized


