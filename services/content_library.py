NICHE_LABELS = {k: v['label'] for k, v in NICHE_PRESETS.items()}


def apply_niche_preset(niche: str, profile_id: str = None) -> bool:
    """Применить пресет ниши к профилю."""
    preset = NICHE_PRESETS.get(niche)
    if not preset:
        return False
    lib = load_library(profile_id)
    lib['entries'] = preset['entries']
    lib['polls']   = preset['polls']
    lib['ctas']    = preset['ctas']
    lib['niche']   = niche
    save_library(lib, profile_id)
    return True


# ── Хранилище (per-profile) ─────────────────────────────────────

def _lib_file(profile_id: str = None) -> Path:
    pid = profile_id or app_state.active_profile_id
    return STORAGE_DIR / pid / 'content_library.json'


def load_library(profile_id: str = None) -> dict:
    f = _lib_file(profile_id)
    if f.exists():
        try:
            return json.loads(f.read_text(encoding='utf-8'))
        except Exception:
            pass
    return _default_lib()


def _default_lib() -> dict:
    return {
        'enabled': False,
        'cta_enabled': False,
        'niche': 'nature',
        'entries': DEFAULT_ENTRIES,
        'polls': DEFAULT_POLLS,
        'ctas': DEFAULT_CTAS,
    }


def save_library(data: dict, profile_id: str = None):
    f = _lib_file(profile_id)
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    except Exception as e:
        logger.warning(f'content_library save: {e}')


def get_random_entry() -> dict:
    """Вернуть случайный вариант текста+хэштегов из библиотеки."""
    lib = load_library()
    entries = lib.get('entries', [])
    if not entries:
        return {'text': '', 'tags': ''}
    return random.choice(entries)


def get_random_cta() -> str:
    """Случайный CTA если включён."""
    lib = load_library()
    if not lib.get('cta_enabled', False):
        return ''
    ctas = lib.get('ctas', DEFAULT_CTAS)
    return random.choice(ctas) if ctas else ''


def get_random_caption(existing_text: str = '', add_tags: bool = True) -> str:
    """
    Сформировать подпись к посту:
    - Если enabled=False — вернуть existing_text без изменений
    - Иначе выбрать случайный текст+хэштеги из библиотеки
    """
    lib = load_library()
    if not lib.get('enabled', False):
        return existing_text

    entry = get_random_entry()
    text = entry.get('text', '')
    tags = entry.get('tags', '') if add_tags else ''
    cta  = get_random_cta()

    parts = [p for p in [text, tags, cta] if p]
    if parts:
        return '\n\n'.join(parts)
    return existing_text


def get_all_polls() -> list:
    lib = load_library()
    return lib.get('polls', DEFAULT_POLLS)
