def _lib_file(profile_id: str = None) -> Path:
    pid = profile_id or app_state.active_profile_id
    return STORAGE_DIR / pid / 'content_library.json'


def _default_lib() -> dict:
    return {
        'enabled': False,
        'cta_enabled': False,
        'universal_mode': True,
        'niche': 'universal',
        'entries': list(UNIVERSAL_ENTRIES),
        'polls': list(DEFAULT_POLLS),
        'ctas': list(UNIVERSAL_CTAS),
    }


def _normalize_library(data: dict) -> dict:
    lib = _default_lib()
    if isinstance(data, dict):
        lib.update(data)

    # Force neutral captions by default, including old saved profile libraries.
    if lib.get('universal_mode', True):
        lib['universal_mode'] = True
        lib['niche'] = 'universal'
        lib['entries'] = list(UNIVERSAL_ENTRIES)
        lib['polls'] = list(DEFAULT_POLLS)
        lib['ctas'] = list(UNIVERSAL_CTAS)

    if not isinstance(lib.get('entries'), list):
        lib['entries'] = list(UNIVERSAL_ENTRIES)
    if not isinstance(lib.get('polls'), list):
        lib['polls'] = list(DEFAULT_POLLS)
    if not isinstance(lib.get('ctas'), list):
        lib['ctas'] = list(UNIVERSAL_CTAS)
    return app_state._repair_human_text(lib)


def load_library(profile_id: str = None) -> dict:
    f = _lib_file(profile_id)
    if f.exists():
        try:
            return _normalize_library(json.loads(f.read_text(encoding='utf-8')))
        except Exception as exc:
            logger.warning(f'content_library load: {exc}')
    return _normalize_library(_default_lib())


def save_library(data: dict, profile_id: str = None):
    f = _lib_file(profile_id)
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(
            json.dumps(_normalize_library(data), ensure_ascii=False, indent=2),
            encoding='utf-8',
        )
    except Exception as exc:
        logger.warning(f'content_library save: {exc}')


def apply_niche_preset(niche: str, profile_id: str = None) -> bool:
    preset = NICHE_PRESETS.get(niche)
    if not preset:
        return False
    lib = load_library(profile_id)
    lib['universal_mode'] = True
    lib['niche'] = 'universal'
    lib['entries'] = list(preset['entries'])
    lib['polls'] = list(preset['polls'])
    lib['ctas'] = list(preset['ctas'])
    save_library(lib, profile_id)
    return True


def get_random_entry() -> dict:
    lib = load_library()
    entries = lib.get('entries') or UNIVERSAL_ENTRIES
    return random.choice(entries) if entries else {'text': '', 'tags': ''}


def get_random_cta() -> str:
    lib = load_library()
    if not lib.get('cta_enabled', False):
        return ''
    ctas = lib.get('ctas') or UNIVERSAL_CTAS
    return random.choice(ctas) if ctas else ''


def _iter_hashtags(value) -> Iterable[str]:
    if not value:
        return []
    if isinstance(value, str):
        items = value.replace('\n', ' ').split()
    else:
        items = []
        for item in value:
            items.extend(str(item).replace('\n', ' ').split())

    tags = []
    for item in items:
        item = item.strip().strip(',')
        if not item:
            continue
        if not item.startswith('#'):
            item = f'#{item}'
        if len(item) > 1:
            tags.append(item)
    return tags


def dedupe_hashtags(*values) -> str:
    result = []
    seen = set()
    for value in values:
        for tag in _iter_hashtags(value):
            key = tag.lower()
            if key in seen:
                continue
            seen.add(key)
            result.append(tag)
    return ' '.join(result)


def compose_caption(
    existing_text: str = '',
    add_tags: bool = True,
    profile_tags=None,
    add_profile_tags: bool = False,
    extra_tags: list[str] | None = None,
) -> str:
    lib = load_library()
    existing_text = (existing_text or '').strip()
    parts = []
    lib_tags = ''

    if lib.get('enabled', False):
        entry = get_random_entry()
        text = (entry.get('text') or '').strip()
        if text:
            parts.append(text)
        if add_tags:
            lib_tags = entry.get('tags', '')
        cta = get_random_cta()
        if cta:
            parts.append(cta.strip())
    elif existing_text:
        parts.append(existing_text)

    all_profile_tags = list(profile_tags or [])
    if extra_tags:
        # Добавляем несколько хештегов от конкурентов (не все — не спамим)
        chosen = random.sample(extra_tags, min(3, len(extra_tags)))
        all_profile_tags.extend(chosen)

    tags = dedupe_hashtags(lib_tags if add_tags else '', all_profile_tags if add_profile_tags else None)
    if tags:
        parts.append(tags)

    return '\n\n'.join(part for part in parts if part).strip()


def get_random_caption(existing_text: str = '', add_tags: bool = True) -> str:
    return compose_caption(existing_text, add_tags=add_tags)


def get_all_polls() -> list:
    lib = load_library()
    return lib.get('polls') or DEFAULT_POLLS
